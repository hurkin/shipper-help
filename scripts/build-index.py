#!/usr/bin/env python3
"""Rebuild docs/context/_sidebar.md and docs/search-paths.js.

Run after adding, removing or retitling a page:

    python scripts/build-index.py

The context sidebar lists every context page alphabetically by its title.
Docsify's search only indexes the sidebar on screen, so search-paths.js gives
it every page linked from any sidebar instead.
"""
import re
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent / "docs"
CONTEXT = DOCS / "context"


def title(page):
    for line in page.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return page.stem


def mnemonic_kind(stem):
    if stem.startswith("M") and stem[1:].isdigit():
        return "mobile"
    if re.fullmatch(r"R\d+|SQL-.+|CUSTREPS", stem):
        return "report"
    return None


def build_context_sidebar():
    pages = [p for p in CONTEXT.glob("*.md") if not p.name.startswith("_") and p.name != "README.md"]
    titles = {p: title(p) for p in pages}
    counts = {}
    for t in titles.values():
        counts[t] = counts.get(t, 0) + 1
    rows = []
    for p, t in titles.items():
        kind = mnemonic_kind(p.stem)
        # Two pages share a title: say which is the mobile screen or the report.
        if counts[t] > 1 and kind:
            t = f"{t} ({kind})"
        rows.append((t.lower(), t, p.name))
    rows.sort()
    lines = ["- [Home](../)", "- **Screen Help**", "  - [Overview](./)"]
    lines += [f"  - [{t}]({name})" for _, t, name in rows]
    (CONTEXT / "_sidebar.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(rows)


def build_search_paths():
    paths = []
    for sidebar in sorted(DOCS.rglob("_sidebar.md")):
        folder = sidebar.parent
        for href in re.findall(r"\]\(([^)\s]+)\)", sidebar.read_text(encoding="utf-8")):
            if re.match(r"[a-z]+:", href):
                continue
            target = (folder / href).resolve()
            rel = target.relative_to(DOCS).as_posix()
            if href.endswith("/") or target.is_dir():
                path = "/" + (rel + "/" if rel != "." else "")
            else:
                path = "/" + re.sub(r"\.md$", "", rel)
            path = path.replace("//", "/")
            if path not in paths:
                paths.append(path)
    body = ",\n".join(f"  '{p}'" for p in paths)
    (DOCS / "search-paths.js").write_text(
        "// Generated by scripts/build-index.py. Every page Docsify search indexes.\n"
        f"window.SEARCH_PATHS = [\n{body}\n];\n", encoding="utf-8")
    return len(paths)


if __name__ == "__main__":
    print(f"context sidebar: {build_context_sidebar()} pages")
    print(f"search paths: {build_search_paths()} pages")
